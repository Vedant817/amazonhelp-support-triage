"""Audit whether the pipeline's internal cross-validation score is honest.

The score matrix reports ``cv macro-F1`` from the intent head's regularisation
search, and it disagrees sharply with held-out evaluation (0.81 vs 0.61 macro-F1
on the same natural class prior). A cross-validation score is supposed to be an
unbiased estimate of generalisation, so a gap that large means one of the two
numbers is not measuring what it claims.

Two candidate explanations are tested here:

1. **Label circularity.** ``build_reply_supervision`` mixes reply-derived labels
   with labels produced by an earlier weak-label model. If those extra labels were
   generated by a model trained on the same features, the model can reproduce them
   from the features alone, and cross-validation over a set containing them is
   optimistic.
2. **Optimistic split.** The search reports the score of the *best* C on the folds
   it selected C with, which is a maximum over candidates and therefore biased
   upward.

Run: python scripts_cv_audit.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import f1_score
from sklearn.model_selection import StratifiedKFold, cross_val_predict

sys.path.insert(0, str(Path(__file__).resolve().parent))

from src.dual_head import DualHeadSupportModel, MiniLMEncoder
from src.model_factory import build_reply_supervision

PAIRS_CSV = "data/processed/amazonhelp_context_pairs.csv"
SEED = 42


def _cv_macro_f1(features, labels, c_value: float = 8.0, metric: str = "macro_f1") -> float:
    """Out-of-fold score, i.e. predictions for rows the fold never trained on."""
    splitter = StratifiedKFold(n_splits=3, shuffle=True, random_state=17)
    estimator = LogisticRegression(
        max_iter=2000, random_state=SEED, C=c_value, solver="liblinear"
    )
    predictions = cross_val_predict(estimator, features, labels, cv=splitter)
    if metric == "accuracy":
        return float(np.mean(predictions == np.asarray(labels)))
    return float(f1_score(labels, predictions, average="macro", zero_division=0))


def main() -> int:
    pairs = pd.read_csv(PAIRS_CSV)
    pairs["conversation_context"] = pairs["conversation_context"].fillna("").astype(str)
    supervision = build_reply_supervision(
        pairs, None, use_probabilistic_intent_labels=True
    )
    labelled = supervision[supervision["intent_label"].notna()].copy()

    print("=" * 78)
    print("  LABEL PROVENANCE")
    print("=" * 78)
    counts = labelled["intent_label_source"].value_counts(dropna=False)
    for source, count in counts.items():
        print(f"  {str(source):<42s} {count:>7d}  ({count / len(labelled):6.2%})")
    print(f"  {'TOTAL':<42s} {len(labelled):>7d}")

    print()
    print("=" * 78)
    print("  OUT-OF-FOLD SCORES BY LABEL SOURCE  (hybrid word+char+MiniLM features)")
    print("=" * 78)
    print(f"  {'subset':<44s} {'rows':>6s} {'macro_f1':>9s} {'accuracy':>9s}")

    encoder = MiniLMEncoder()
    vectorizer = DualHeadSupportModel._make_vectorizer()

    subsets = [("all labels", labelled)]
    for source in counts.index:
        subsets.append((f"only {source}", labelled[labelled["intent_label_source"] == source]))
    reply_derived = labelled[
        labelled["intent_label_source"].isin(["reply_weak", "human_reviewed"])
    ]
    subsets.append(("reply-derived only (no model labels)", reply_derived))

    results = {}
    for name, frame in subsets:
        if len(frame) < 60:
            print(f"  {name:<44s} {len(frame):>6d}  (too few rows)")
            continue
        texts = frame["customer_text"].fillna("").astype(str).tolist()
        lexical = vectorizer.fit_transform(texts)
        from scipy.sparse import csr_matrix, hstack

        features = hstack([lexical, csr_matrix(encoder.encode(texts))], format="csr")
        labels = frame["intent_label"].tolist()
        macro = _cv_macro_f1(features, labels)
        accuracy = _cv_macro_f1(features, labels, metric="accuracy")
        results[name] = (macro, accuracy)
        print(f"  {name:<44s} {len(frame):>6d} {macro:>9.4f} {accuracy:>9.4f}")

    print()
    print("=" * 78)
    print("  READING")
    print("=" * 78)
    print("  If the model-generated subset scores far above the reply-derived subset,")
    print("  its labels are reproducible from features the model already sees, so they")
    print("  inflate any score computed over a label set that contains them. The fix")
    print("  is to report and tune on reply-derived labels only.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
